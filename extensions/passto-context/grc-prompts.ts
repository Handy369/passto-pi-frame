    "- 决策内容 → 原因（列表）",
    "",
    "## 修改的文件",
    "- 文件路径: 改动说明（列表）",
    "",
    "## 当前状态",
    "工作进展到哪里了（1-2句）",
    "",
    "## 下一步",
    "接下来应该做什么（1-3项）",
    "",
